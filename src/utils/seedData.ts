export const createDemoState = (): AppState => {
  // Calculate initial balances from demo expenses
  const totalCashSpent = seedExpenses
    .filter(e => e.paymentMode === 'cash')
    .reduce((sum, e) => sum + e.amount, 0);
  const totalDigitalSpent = seedExpenses
    .filter(e => e.paymentMode !== 'cash')
    .reduce((sum, e) => sum + e.amount, 0);

  // Adjust family member wallets for seed transactions
  const adjustedFamilyMembers = seedFamilyMembers.map(fm => {
    const spent = seedFamilyTransactions
      .filter(ft => ft.familyMemberId === fm.id && ft.type === 'withdrawal')
      .reduce((sum, ft) => sum + ft.amount, 0);
    return { ...fm, walletBalance: fm.monthlyBudget - spent };
  });

  return {
    isSetupComplete: true,
    shopProfile: {
      shopName: 'Gupta General Store',
      gallaBalance: 250000 - totalCashSpent,
      bankBalance: 500000 - totalDigitalSpent,
      openingGallaBalance: 250000,
      openingBankBalance: 500000,
    },
    expenses: seedExpenses,
    employees: seedEmployees,
    employeeAdvances: seedAdvances,
    monthlySettlements: [],
    familyMembers: adjustedFamilyMembers,
    familyTransactions: seedFamilyTransactions,
    recurringBills: seedRecurringBills,
    darkMode: false,
    activeTab: 'dashboard',
  };
};
