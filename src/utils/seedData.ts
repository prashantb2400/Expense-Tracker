// Helper: date in current month
const d = (day: number, hour = 10, min = 0): string => {
  const date = new Date(now.getFullYear(), now.getMonth(), day, hour, min);
  if (date > now) date.setMonth(date.getMonth() - 1);
  return date.toISOString();
};

// Helper: date in previous month
const dLast = (day: number, hour = 10): string => {
  const date = new Date(now.getFullYear(), now.getMonth() - 1, day, hour);
  return date.toISOString();
};

